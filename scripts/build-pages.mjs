// Generates the static, crawlable pages (services, service area, about, faq, contact)
// from the content already in index.html, so wording stays in one place.
// Run: node scripts/build-pages.mjs   (from the repo root)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SITE = 'https://www.mjmovingco.com';
const src = readFileSync('index.html', 'utf8');

/* ---------- pull the site's own data out of index.html ---------- */
const grab = (re, label) => { const m = src.match(re); if (!m) throw new Error('not found: ' + label); return m[1]; };
const SERVICES = new Function('return (' + grab(/const SERVICES = (\{[\s\S]*?\n\});\n/, 'SERVICES') + ')')();
const REGIONS = JSON.parse(grab(/const REGIONS = (\[.*?\]);\n/s, 'REGIONS'));
const FAQ = new Function('return (' + grab(/const FAQ = (\[[\s\S]*?\n\]);\n/, 'FAQ') + ')')();
const ICON = new Function('return (' + grab(/const ICON = (\{[\s\S]*?\n\});\n/, 'ICON') + ')')();

const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const PATH = { moving: 'local-moving', packing: 'packing-and-unpacking', 'junk-removal': 'junk-removal', storage: 'storage', 'tv-mounting': 'tv-mounting', supplies: 'moving-supplies' };
const svcPath = k => '/services/' + PATH[k];
const regionSlug = r => slug(r.name);
const regionPath = r => '/service-area/' + regionSlug(r);
const TOTAL_TOWNS = REGIONS.reduce((n, r) => n + r.towns.length, 0);

/* ---------- shared css + header/footer taken from index.html ---------- */
const css = [...src.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m => m[1]).join('\n');
const pageCss = `
.town-list{columns:3 190px;column-gap:28px;list-style:none;padding:0;margin:0}
.town-list li{padding:3px 0;break-inside:avoid;font-weight:500}
.region-card{display:grid;gap:12px}
.region-card + .region-card{margin-top:34px}
.mini-links{list-style:none;padding:0;margin:0;display:grid;gap:2px}
.mini-links a{display:inline-block;padding-block:6px}
.prose p{margin:0}
`;
writeFileSync('site.css', '/* Generated by scripts/build-pages.mjs from index.html. Do not edit by hand. */\n' + css + '\n' + pageCss);

const HASH = { home: '/', services: '/services', areas: '/service-area', about: '/about', faq: '/faq', contact: '/contact', quote: '/#quote' };
const fixLinks = html => html
  .replace(/href="#([a-z0-9-]+)"/g, (m, h) => {
    if (HASH[h]) return `href="${HASH[h]}"`;
    const k = Object.keys(PATH).find(k => k === h);
    if (k) return `href="${svcPath(k)}"`;
    return `href="/#${h}"`;
  })
  .replace(/(src|poster)="(?!https?:|\/|data:)/g, '$1="/');

const svgSprite = grab(/(<svg width="0" height="0"[\s\S]*?<\/svg>)\n<header/, 'svg');
const headerHtml = fixLinks(grab(/(<header class="top">[\s\S]*?<\/header>)/, 'header'));
const mbarHtml = fixLinks(grab(/(<div class="mbar"[\s\S]*?<\/div>)\n<footer>/, 'mbar'));

const popular = ['Boston', 'Cambridge', 'Somerville', 'Brookline', 'Newton', 'Quincy', 'Waltham', 'Medford'];
const regionOf = t => REGIONS.find(r => r.towns.includes(t));
let footerHtml = fixLinks(grab(/(<footer>[\s\S]*?<\/footer>)/, 'footer'));
footerHtml = footerHtml
  .replace('<ul id="footSvc"></ul>', '<ul>' + Object.keys(SERVICES).map(k => `<li><a href="${svcPath(k)}">${esc(SERVICES[k].title)}</a></li>`).join('') + '</ul>')
  .replace('<ul id="footAreas"></ul>', '<ul>' + popular.map(t => `<li><a href="${regionPath(regionOf(t))}">${t}</a></li>`).join('') + '<li><a href="/service-area">All towns →</a></li></ul>')
  .replace('<span id="yr"></span>', '<span id="yr">2026</span>');

/* ---------- helpers ---------- */
const svcCard = k => { const s = SERVICES[k]; return `<a class="svc label" href="${svcPath(k)}"><span class="lbl">
  <span class="lbl-top"><span>Handle with care</span><span class="up" aria-hidden="true">↑↑</span></span>
  <span class="lbl-row"><span class="ico">${ICON[s.icon]}</span><span><small>Contents</small><h3>${esc(s.title)}</h3></span></span>
  <p>${esc(s.short)}</p>
  <span class="lbl-foot"><span class="barcode" aria-hidden="true"></span><span class="more">See service →</span></span></span></a>`; };
const faqHtml = list => list.map(([q, a]) => `<details><summary>${q}</summary><p>${a}</p></details>`).join('');
const tapeText = ['MJ Moving Company', 'Handle with care', 'Open 24/7', '<a class="tel" href="tel:+15082156322">508-215-6322</a>', 'This side up', 'Serving Massachusetts and beyond'];
const tape = `<div class="tape" aria-hidden="true"><div class="tapeClone">${[...tapeText, ...tapeText, ...tapeText, ...tapeText].map(t => `<span>${t}</span>`).join('')}</div></div>`;
const crumbs = items => `<span class="crumb">${items.map(([l, h]) => h ? `<a href="${h}">${l}</a>` : l).join(' / ')}</span>`;
const pageHead = (cr, h1, lead, cta) => `<section class="page-head quilt"><div class="wrap">
    ${cr}
    <h1>${h1}</h1><p class="lead">${lead}</p>
    ${cta ? `<p><a class="btn" href="/#quote">${cta}</a></p>` : ''}
  </div></section>
  ${tape}`;

const provider = { '@type': 'MovingCompany', name: 'MJ Moving Company', url: SITE + '/', telephone: '+1-508-215-6322' };
const breadcrumbLd = items => ({ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: items.map(([name, path], i) => ({ '@type': 'ListItem', position: i + 1, name, item: SITE + path })) });

function page({ path, title, description, body, ld = [] }) {
  const url = SITE + path;
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${url}">
<meta name="theme-color" content="#13275C">
<meta property="og:type" content="website">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${SITE}/og-share.jpg">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="/favicon.png" type="image/png">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,500..900&family=Hanken+Grotesk:wght@400;500;600;700&family=IBM+Plex+Mono:wght@500;600&display=swap">
<link rel="stylesheet" href="/site.css">
${ld.map(o => `<script type="application/ld+json">${JSON.stringify(o)}</script>`).join('\n')}
</head>
<body>
${svgSprite}
${headerHtml}
<main>
${body}
</main>
${mbarHtml}
${footerHtml}
<script src="/pages.js" defer></script>
</body>
</html>
`;
  const file = path.replace(/^\//, '') + '.html';
  if (file.includes('/')) mkdirSync(file.slice(0, file.lastIndexOf('/')), { recursive: true });
  writeFileSync(file, html);
  return { path, file };
}

